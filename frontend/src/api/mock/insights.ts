import type { EvidenceItem, EvidenceSourceAgent, Insight, ReviewEvent } from '@/api/types'

/**
 * Synthesized outputs of the agent orchestrator (agents/orchestrator.py),
 * built on top of the transcribed evidence in seed.ts so every citation
 * (evidence code, note id) resolves to a real underlying record. Category
 * mirrors the backend's 4-value research contract; subtype is the finer
 * risk/opportunity driver the orchestrator's prompts explicitly require
 * distinguishing (see rag/risk_classifier.py's split between relationship,
 * project/implementation, and operational risk).
 */

function ev(
  sourceAgent: EvidenceSourceAgent,
  evidenceCode: string,
  label: string,
  detail: string,
  date: string,
  semantics?: Pick<EvidenceItem, 'riskTypes' | 'supportedClaims' | 'metricType'>,
): EvidenceItem {
  return {
    id: `EV_${evidenceCode}`,
    sourceAgent,
    sourceType: sourceAgent === 'external_data_agent' ? 'external' : 'internal',
    evidenceCode,
    label,
    detail,
    date,
    ...semantics,
  }
}

function generatedEvent(timestamp: string): ReviewEvent {
  return { id: `${timestamp}_generated`, action: 'generated', actor: 'system', timestamp }
}

